import { AudioProduct, PortSpec } from '../types/audio';

function createPorts(
  prefix: string,
  labelPrefix: string,
  count: number,
  direction: 'in' | 'out',
  signalType: PortSpec['signalType'],
  connector: PortSpec['connector'],
  startIndex = 1,
  withAmpChannel = false
): PortSpec[] {
  return Array.from({ length: count }, (_, idx) => {
    const ch = startIndex + idx;
    return {
      id: `${prefix}_${ch}`,
      label: `${labelPrefix}${ch}`,
      direction,
      signalType,
      connector,
      channelIndex: ch,
      ampChannel: withAmpChannel ? ch : undefined,
    };
  });
}

